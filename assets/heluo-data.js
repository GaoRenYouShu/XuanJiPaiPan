/* 三元：1864 起每元 60 年，180 年一周（2044 起回上元）。
 * 元界口径由 heluo.js 传入的立春界年份决定，此处只给分段函数 */
function HL_sanyuanOf(y){
  const m=((y-1864)%180+180)%180;
  return Math.floor(m/60); /* 0 上元、1 中元、2 下元 */
}

/* 中宫寄卦（含阴阳年细分）：上元男艮女坤；中元阳男阴女艮、阴男阳女坤；
 * 下元男离女兑。yuan:0 上、1 中、2 下；isYangYear 年干阴阳；male 性别 */
function HL_zhonggong(yuan,isYangYear,male){
  if(yuan===0) return male?'艮':'坤';
  if(yuan===2) return male?'离':'兑';
  /* 中元：阳男阴女寄艮，阴男阳女寄坤 */
  return (isYangYear===male)?'艮':'坤';
}

