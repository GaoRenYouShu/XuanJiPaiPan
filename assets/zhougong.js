/* 吉凶判读：显式补充表最优先；其余按 同句吉凶并见判兼、凶义随去除散解而消反为吉、
   强吉辞优先于凶辞、凶辞、吉辞 的顺序判定，皆不中返回 null */
function zgLuck(text){
  if (ZG_LUCK_OVERRIDE.hasOwnProperty(text)) return ZG_LUCK_OVERRIDE[text];
  if (/吉/.test(text) && /凶/.test(text)) return 0;
  if (/(凶|病|疾|患|忧|灾|厄|险|难|耻|辱|口舌|孝|囚|恶|悲|谗)[^，。]*(去|除|散|解|脱)$/.test(text)) return 1;
  if (/病患不生$/.test(text) || /不出凶$/.test(text) || /恶事无$/.test(text) || /官事明$/.test(text)) return 1;
  if (/讼(有理|得理)$/.test(text)) return 1;
  if (ZG_JI_STRONG.test(text)) return 1;
  if (ZG_XIONG.test(text)) return -1;
  if (ZG_JI.test(text)) return 1;
  return null;
}

/* 主体梦象：各类字表中取命中位置最早者，同位取最长者；无命中归总论 */
function zgSubject(cat, img){
  var list = ZG_SUBJECTS[cat] || [];
  var best = null, bestPos = 99, bestLen = 0;
  list.forEach(function(s){
    var p = img.indexOf(s);
    if (p < 0) return;
    if (p < bestPos || (p === bestPos && s.length > bestLen)) {
      best = s; bestPos = p; bestLen = s.length;
    }
  });
  best = (best && ZG_SUB_ALIAS[best]) || best;
  return best || '总论';
}

/* 检索：去梦见、梦到前缀，同义词组展开，完全、前缀、包含三级计分，门类聚簇 */
function zgSearch(q){
  q = (q || '').replace(/^梦(见|到|了)?/, '').replace(/^\s+|\s+$/g, '');
  if (!q) return [];
  var terms = [q];
  ZG_SYNS.forEach(function(g){
    var hit = g.some(function(t){ return t === q || q.indexOf(t) >= 0; });
    if (hit) g.forEach(function(t){ if (terms.indexOf(t) < 0) terms.push(t); });
  });
  var out = [];
  ZG_ROWS.forEach(function(r){
    var best = 0;
    terms.forEach(function(t, i){
      var w = i === 0 ? 1 : 0.85, s = 0;
      if (r.text === t) s = 100;
      else if (r.img === t) s = 92;
      else if (r.omen === t) s = 88;
      else if (r.text.indexOf(t) === 0) s = 70;
      else if (r.img.indexOf(t) === 0) s = 64;
      else if (r.text.indexOf(t) >= 0) s = 50;
      else if (r.img.indexOf(t) >= 0) s = 46;
      else if (t.length >= 2) {
        /* 模糊档：整词不中时按二字滑窗切词，全部切词命中词条或梦象给 34 分、过半命中给 22 分 */
        var grams = t.length - 1, hits = 0, g;
        for (g = 0; g < t.length - 1; g++) {
          var gm = t.substring(g, g + 2);
          if (r.text.indexOf(gm) >= 0 || r.img.indexOf(gm) >= 0) hits++;
        }
        if (hits === grams) s = 34;
        else if (hits * 2 >= grams) s = 22;
      }
      if (s * w > best) best = s * w;
    });
    if (best > 0) out.push({ row: r, score: best });
  });
  out.sort(function(a, b){
    if (b.score !== a.score) return b.score - a.score;
    if (a.row.cat !== b.row.cat) return a.row.cat - b.row.cat;
    return a.row.ci - b.row.ci;
  });
  return out.slice(0, 60).map(function(x){ return x.row; });
}

/* 无结果时的字面相关条目：按检索词与条目文本的最长连续重合片段计分，
   纯字面匹配，不含任何语义推断。页面须明确标注为"字面相关、非此象"后方可展示，
   不得充当所问梦象的占辞。 */
function zgNeighbors(q){
  q = (q || '').replace(/^梦(见|到|了)?/, '').replace(/^\s+|\s+$/g, '');
  if (!q) return [];
  var scored = ZG_ROWS.map(function(r){
    var longest = 0, n = 0;
    for (var i = 0; i < q.length; i++) {
      for (var j = q.length - i; j > 0; j--) {
        var seg = q.substr(i, j);
        if (r.text.indexOf(seg) >= 0) { n += j * j; if (j > longest) longest = j; break; }
      }
    }
    return { row: r, n: n, longest: longest };
  });
  scored = scored.filter(function(x){ return x.longest > 0; });
  scored.sort(function(a, b){ return b.longest - a.longest || b.n - a.n || a.row.ci - b.row.ci; });
  return scored.slice(0, 8).map(function(x){ return x.row; });
}

