/* 现代梦象桥接查询：完全命中优先，其次双向包含匹配，返回 {terms, why} 或 null */
function zgModernMatch(q){
  q = (q || '').replace(/^梦(见|到|了)?/, '').replace(/^\s+|\s+$/g, '');
  if (q.length < 2) return null;
  for (var i = 0; i < ZG_MODERN.length; i++) {
    if (ZG_MODERN[i][0] === q) return { terms: ZG_MODERN[i][1], why: ZG_MODERN[i][2] };
  }
  for (var j = 0; j < ZG_MODERN.length; j++) {
    var k = ZG_MODERN[j][0];
    if (q.indexOf(k) >= 0 || k.indexOf(q) >= 0) return { terms: ZG_MODERN[j][1], why: ZG_MODERN[j][2] };
  }
  return null;
}

/* 规模统计：类数、条数、吉凶兼分布、各主体分布 */
function zgStats(){
  var s = { cats: ZG_CATS.length, total: ZG_ROWS.length, ji: 0, xiong: 0, jian: 0, unknown: 0 };
  ZG_ROWS.forEach(function(r){
    if (r.luck === 1) s.ji++;
    else if (r.luck === -1) s.xiong++;
    else if (r.luck === 0) s.jian++;
    else s.unknown++;
  });
  return s;
}

