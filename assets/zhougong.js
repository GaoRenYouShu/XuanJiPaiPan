/* 某类按主体梦象聚组的条目 */
function zgCatGroups(cat){
  var groups = [], idx = {};
  ZG_ROWS.forEach(function(r){
    if (r.cat !== cat) return;
    if (!idx[r.sub]) { idx[r.sub] = []; groups.push({ sub: r.sub, items: [] }); }
    idx[r.sub].push(r);
  });
  groups.forEach(function(g){ idx[g.sub].forEach(function(r){ g.items.push(r); }); });
  return groups;
}
